#!/bin/sh
# gen_icons.sh generates internal/gui/glyphs_gen.go from the Remix Icon
# package (icons rendered with the app's UI inherit the text color, so the
# SVGs keep fill="currentColor"). Run from app/: sh tools/gen_icons.sh
set -e

ICONS="tools/node_modules/remixicon/icons"
OUT="internal/gui/glyphs_gen.go"

# icon variable -> Remix Icon file (Remix Icon only, -line for interface
# icons, -fill for the active tray variants)
names="icTimer System/timer-line
icTimerFill System/timer-fill
icMoon Weather/moon-line
icMoonFill Weather/moon-fill
icClock System/time-line
icClockFill System/time-fill
icHourglass System/hourglass-line
icHourglassFill System/hourglass-fill
icDrop Design/drop-line
icDropFill Design/drop-fill
icCup Food/cup-line
icPlay Media/play-line
icPause Media/pause-line
icReset Device/restart-line
icSkip Media/skip-forward-line
icChevron Arrows/arrow-right-s-line
icAlert System/alert-line
icInfo System/information-line
icRefresh System/refresh-line
icServer Device/server-line
icChart Business/bar-chart-2-line
icFire Weather/fire-line
icMedal Business/medal-line
icTrophy Finance/trophy-line
icCalendar Business/calendar-line
icSettings System/settings-3-line
icVolume Media/volume-up-line
icBell Media/notification-3-line
icBulb Others/lightbulb-line
icAdd System/add-line
icSubtract System/subtract-line
icClose System/close-line
icCheck System/check-line
icExport System/download-2-line
icTrash System/delete-bin-line
icQuit Device/shut-down-line
icExternal System/external-link-line
icKeyboard Device/keyboard-line
icLock System/lock-line
icEye System/eye-line
icWalk Map/walk-line
icLeaf Others/leaf-line
icPulse Weather/flashlight-line"

{
  echo "// Code generated by tools/gen_icons.sh; DO NOT EDIT."
  echo
  echo "package gui"
  echo
  echo "import ("
  echo $'\t'"\"github.com/egoist/mygo/ui\""
  echo ")"
  echo
  echo "// Icons from Remix Icon 4.9.1 (Apache-2.0), -line style: they inherit"
  echo "// the color of the text beside them."
  echo "var ("
  echo "$names" | while IFS=' ' read -r var path; do
    [ -z "$var" ] && continue
    # undo the quoting of paths with spaces
    path=$(echo "$path" | sed "s/^'//; s/'\$//; s/\\\\ / /g")
    svg=$(cat "$ICONS/$path.svg")
    echo $'\t'"$var = ui.MustParseSVG([]byte(\`$svg\`))"
  done
  echo ")"
} > "$OUT"

gofmt -w "$OUT"
echo "wrote $OUT"
